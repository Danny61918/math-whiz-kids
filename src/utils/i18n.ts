export const translations: Record<Language, Record<TranslationKey, string>> = {
    'zh-TW': zhTW,
    en,
};

export function t(key: TranslationKey, lang: Language): string {
    return translations[lang][key] || translations.en[key] || key;
}

/** Like t(), replacing {name} placeholders with the given values. */
export function tp(key: TranslationKey, lang: Language, vars: Record<string, string | number>): string {
    return Object.entries(vars).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), t(key, lang));
}
