function build(category: CardCategory, rows: Row[], hueOffset: number): Card[] {
    return rows.map(([key, rarity, nameEn, nameZh, emoji], i) => ({
        id: `${category}_${key}`,
        category,
        rarity,
        nameEn,
        nameZh,
        emoji,
        hue: (hueOffset + i * 47) % 360,
    }));
}

