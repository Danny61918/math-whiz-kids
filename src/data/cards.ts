export type CardCategory = 'dino' | 'car' | 'plane' | 'ship_train' | 'space' | 'rescue';

export interface Card {
    id: string;
    category: CardCategory;
    rarity: 1 | 2 | 3 | 4;
    nameEn: string;
    nameZh: string; // zh-TW wording as used in Taiwan
    emoji: string;
    hue?: number; // 0-359, background tint so siblings with the same emoji look different
    /**
     * Optional image URL. When present it replaces the emoji.
     * NOTE: all art is currently emoji PLACEHOLDER art, to be replaced by real illustrations later.
     */
    art?: string;
}

